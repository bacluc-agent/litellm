#!/usr/bin/env bash
set -euo pipefail

readonly MODEL_PRICES_URL='https://raw.githubusercontent.com/BerriAI/litellm/refs/heads/main/model_prices_and_context_window.json'
readonly MODEL_PREFIX='opencode_go/'

usage() {
  printf 'Usage: %s [values-file]\n' "${0##*/}" >&2
  exit 2
}

case "$#" in
  0)
    values_file="$(cd "$(dirname "$0")/.." && pwd)/values-vshn-llm-routing.yaml"
    ;;
  1)
    values_file=$1
    ;;
  *)
    usage
    ;;
esac

prices_file=$(mktemp)
trap 'rm -f "$prices_file"' EXIT
curl -fsSL "$MODEL_PRICES_URL" -o "$prices_file"

python3 - "$prices_file" "$values_file" "$MODEL_PREFIX" <<'PYEOF'
import json
import math
import re
import sys

prices_file, values_file, model_prefix = sys.argv[1], sys.argv[2], sys.argv[3]

BLOCK_BEGIN = '  # BEGIN GENERATED opencodeModelParams (generated by scripts/sync-model-params.sh — do not edit by hand)'
BLOCK_END = '  # END GENERATED opencodeModelParams'
FIXED_KEYS = (
    'max_input_tokens',
    'max_output_tokens',
    'input_cost_per_token',
    'output_cost_per_token',
    'cache_read_input_token_cost',
    'cache_creation_input_token_cost',
)
SKIP_KEYS = frozenset((
    'litellm_provider',
    'source',
    'mode',
    'api_base',
    'supported_endpoints',
    'tiered_pricing',
))
BEGIN_RE = re.compile(r'^\s*# BEGIN GENERATED opencodeModelParams\b')
END_RE = re.compile(r'^\s*# END GENERATED opencodeModelParams\b')
LEGACY_RE = re.compile(r'^(\s*)opencodeModelInfo:\s*$')
MODELS_RE = re.compile(r'^(\s*)-\s+(\S+)\s*$')

with open(prices_file) as f:
    prices = json.load(f)

with open(values_file) as f:
    lines = f.read().splitlines()

models = []
models_indent = None
for i, line in enumerate(lines):
    if re.match(r'^\s*opencodeModels:\s*$', line):
        models_indent = len(line) - len(line.lstrip())
        for line in lines[i + 1:]:
            stripped = line.strip()
            if not stripped or stripped.startswith('#'):
                continue
            indent = len(line) - len(line.lstrip())
            if indent <= models_indent:
                break
            match = MODELS_RE.match(line)
            if match and line.lstrip()[0] == '-':
                models.append(match.group(2))
        break
if models_indent is None:
    sys.exit('sync-model-params.sh: no opencodeModels block found in %s' % values_file)

copies = {}
errors = []
for model in models:
    entry = prices.get(model_prefix + model)
    if entry is None:
        errors.append('model %r: no %s%s entry in the model_prices file' % (model, model_prefix, model))
        continue
    picked = {}
    for key in sorted(entry):
        value = entry[key]
        if key in SKIP_KEYS:
            continue
        if key in FIXED_KEYS or key.startswith('supports_') or key.startswith('budget') or 'cost' in key:
            if value is None or isinstance(value, (list, dict)):
                errors.append('model %r: key %r has unsupported type %s' % (model, key, type(value).__name__))
                continue
            if isinstance(value, float) and not math.isfinite(value):
                errors.append('model %r: key %r is not a finite float' % (model, key))
                continue
            if 'cost' in key and isinstance(value, int) and not isinstance(value, bool):
                value = float(value)
            picked[key] = value
    if not picked:
        errors.append('model %r: zero fields copied from %s%s' % (model, model_prefix, model))
        continue
    copies[model] = picked
if errors:
    sys.stderr.write('sync-model-params.sh: failed to sync %d of %d models:\n' % (len(errors), len(models)))
    for error in errors:
        sys.stderr.write('  - %s\n' % error)
    sys.exit(1)


def field(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    s = repr(float(v)).replace('E', 'e')
    mant, _, exp = s.partition('e')
    if exp and '.' not in mant:
        mant += '.0'
    return mant + 'e' + exp if exp else s


block = [BLOCK_BEGIN, '  opencodeModelParams:']
for model in sorted(copies):
    block.append('    %s:' % model)
    for key in sorted(copies[model]):
        block.append('      %s: %s' % (key, field(copies[model][key])))
block.append(BLOCK_END)

begins = [i for i, line in enumerate(lines) if BEGIN_RE.match(line)]
ends = [i for i, line in enumerate(lines) if END_RE.match(line)]
if len(begins) > 1 or len(ends) > 1 or bool(begins) != bool(ends) or (begins and begins[0] >= ends[0]):
    sys.exit(
        'sync-model-params.sh: generated block markers in %s are ambiguous '
        '(found %d BEGIN, %d END markers)' % (values_file, len(begins), len(ends))
    )

if begins:
    lines[begins[0]:ends[0] + 1] = block
else:
    legacy = [
        (i, len(lines[i]) - len(lines[i].lstrip()))
        for i, line in enumerate(lines)
        if LEGACY_RE.match(line)
    ]
    if len(legacy) > 1:
        sys.exit('sync-model-params.sh: multiple legacy opencodeModelInfo blocks in %s' % values_file)
    if not legacy:
        sys.exit(
            'sync-model-params.sh: no generated opencodeModelParams markers and no '
            'legacy opencodeModelInfo block found in %s' % values_file
        )
    key_index, key_indent = legacy[0]
    end = len(lines)
    for i in range(key_index + 1, len(lines)):
        stripped = lines[i].strip()
        if not stripped or stripped.startswith('#'):
            continue
        if len(lines[i]) - len(lines[i].lstrip()) < key_indent:
            end = i
            break
    lines[key_index:end] = block
with open(values_file, 'w') as f:
    f.write('\n'.join(lines) + '\n')

print('sync-model-params.sh: wrote %d models to %s' % (len(copies), values_file))
PYEOF
